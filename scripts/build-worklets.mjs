// Builds the static AudioWorklet module public/worklets/ltc-decoder.js from its TypeScript sources
// (src/lib/sync/ltc.ts, the decoder core, and src/lib/sync/ltc-worklet.ts, the processor), so the
// decoder that vitest tests is byte for byte the one the browser runs. Next serves the public
// folder as is, and an AudioWorklet module must be one self-contained script.
//
//   node scripts/build-worklets.mjs          write the file
//   node scripts/build-worklets.mjs --check  exit 1 when the file is out of date
//
// src/lib/sync/ltc-worklet.test.ts fails when the committed file differs from what this builds.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const WORKLET_OUT = path.join(ROOT, "public/worklets/ltc-decoder.js");
const SOURCES = ["src/lib/sync/ltc.ts", "src/lib/sync/ltc-worklet.ts"];

function transpile(file) {
  const source = fs.readFileSync(path.join(ROOT, file), "utf8");
  const { outputText } = ts.transpileModule(source, {
    fileName: file,
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: false, useDefineForClassFields: false },
  });
  return (
    outputText
      // the two files become one script: no module syntax between them
      .replace(/^import\s[^;]*;\s*$/gm, "")
      .replace(/^export\s+(?=(class|function|const|let)\b)/gm, "")
      .replace(/^export\s*\{\s*\};?\s*$/gm, "")
      .trimEnd()
  );
}

/** The generated worklet module (a string). */
export function buildLtcWorklet() {
  const parts = SOURCES.map((file) => `// ---- ${file}\n${transpile(file)}`);
  return `// Generated by scripts/build-worklets.mjs from ${SOURCES.join(" and ")}. Do not edit: change the\n// sources and run \`node scripts/build-worklets.mjs\`.\n\n${parts.join("\n\n")}\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const next = buildLtcWorklet();
  const current = fs.existsSync(WORKLET_OUT) ? fs.readFileSync(WORKLET_OUT, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error(`${path.relative(ROOT, WORKLET_OUT)} is out of date: run node scripts/build-worklets.mjs`);
      process.exit(1);
    }
    console.log(`${path.relative(ROOT, WORKLET_OUT)} is up to date`);
  } else {
    fs.mkdirSync(path.dirname(WORKLET_OUT), { recursive: true });
    fs.writeFileSync(WORKLET_OUT, next);
    console.log(`wrote ${path.relative(ROOT, WORKLET_OUT)} (${next.length} bytes)`);
  }
}
